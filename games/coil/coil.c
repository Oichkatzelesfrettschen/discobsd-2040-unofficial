/*
 * coil -- a chain shooter for the PicoCalc console of the DiscoBSD RP2040
 * port (53 columns by 32 rows, ANSI escapes; it also fits 80 by 24).
 * Colored balls enter at the outer end of a spiral path and creep toward
 * its center. A launcher in the middle of the field turns through sixteen
 * directions and fires one ball along a straight line; the ball stops at
 * the first chain ball the line meets and joins the chain there. Three or
 * more neighbors of one color vanish, the part of the chain behind the
 * hole rolls forward to close it, and when the two ends meet with equal
 * colors the run they form can vanish in turn. The level is won when the
 * path is empty and no ball is left to enter, and lost when the front of
 * the chain reaches the last cell of the path. Written from the rules of
 * the genre alone.
 *
 * usage: coil [-m] [level [seed]]
 *
 *   -m     monochrome: balls print as glyph pairs without color
 *   level  1..9, default 1: more balls, more colors, faster creep
 *   seed   random seed, default time(NULL) and getpid()
 *
 * Keys: Left/Right (h, l) turn the launcher one step, Down (j) turns it to
 * the opposite side, Up (k), Space or Enter fires, p, F1 or Esc pause, Ctrl-L
 * repaints, q quits. After a level ends, Space or Enter starts the next
 * level with the score kept (the same level and a zero score after a loss).
 *
 * The file has two halves. The rules (path, aim line, insertion, runs, gap
 * closing, scoring, clock) perform no I/O and read no clock: time enters
 * through cl_tick(), one call per CL_TICK_MS. Defining COIL_LOGIC compiles
 * that half alone so tests/logic_test.c can include this file. The second
 * half is the terminal front end, built on games/gameterm.h.
 *
 * Path and chain. The path is CL_PATHLEN cells of a CL_W by CL_H field,
 * generated by a turtle that walks clockwise from the top-left corner and
 * turns right at the edge or one cell before an earlier lap, which leaves
 * a one-cell lane between laps. Ball k of the chain stands on path cell
 * pos[k]; k = 0 is the front, positions fall strictly with k, and a
 * difference above 1 is a gap. While no gap exists the chain advances one
 * cell every adv_ticks ticks and a new ball enters at cell 0 behind it (the
 * advance has just cleared that cell).
 * While a gap exists the front part holds and every part behind a gap rolls
 * one cell per tick toward the part ahead.
 *
 * Testing hook: if GAMEBOX_TEST is set, time stops: a '.' key is one tick
 * and the chain advances on every tick. The value is "spawn[/shots]", each
 * a string of the digits 1 to 5: the spawn string is the whole supply, in
 * order, and the shot string is repeated; shots default to the spawn string
 * and an unusable value selects "12". The seed is ignored.
 */
#include <stdlib.h>
#include <string.h>

/* ------------------------------------------------------------------ */
/* Rules                                                              */
/* ------------------------------------------------------------------ */

#define CL_W		23
#define CL_H		17
#define CL_PATHLEN	150
#define CL_MAXB		CL_PATHLEN
#define CL_NCOL		5
#define CL_NDIR		16
#define CL_LX		(CL_W / 2)	/* launcher cell */
#define CL_LY		(CL_H / 2)
#define CL_TICK_MS	50
#define CL_LEVEL_MAX	9
#define CL_SCORE_MAX	99999999UL

enum { CL_PLAY, CL_WON, CL_LOST };

/*
 * Sixteen aim directions in steps of 22.5 degrees, clockwise from up, as
 * (dx, dy) with y growing down. The ratios 2:5, 1:1 and 5:2 stand for
 * 22.5, 45 and 67.5 degrees.
 */
static const signed char cl_dir[CL_NDIR][2] = {
	{ 0, -1 }, { 2, -5 }, { 1, -1 }, { 5, -2 },
	{ 1, 0 }, { 5, 2 }, { 1, 1 }, { 2, 5 },
	{ 0, 1 }, { -2, 5 }, { -1, 1 }, { -5, 2 },
	{ -1, 0 }, { -5, -2 }, { -1, -1 }, { -2, -5 }
};

static short cl_path[CL_PATHLEN][2];	/* x, y of each path cell */
static short cl_idx[CL_H][CL_W];	/* path index of a cell, or -1 */

struct cl_game {
	int n;				/* balls on the path */
	unsigned char col[CL_MAXB];	/* color 1..CL_NCOL of ball k */
	short pos[CL_MAXB];		/* path cell of ball k */
	int supply;			/* balls still to enter */
	int ncol;			/* colors in play */
	int adv_ticks, clock;		/* ticks per advance, ticks since */
	int combo;			/* 0, 1 for a shot's clear, 2.. for rejoins */
	int level, dir, shot, next, state;
	unsigned long score;
	const char *spawn_script;	/* the supply in order, or NULL */
	const char *shot_script;	/* repeated shot colors, or NULL */
	int spawn_at, shot_at;
	int (*draw)(int);		/* draw(m) returns 0..m-1 */
};

/* Would stepping from (x, y) by (dx, dy) leave the field, enter a cell the
 * walk used, or come within one cell of one it used? */
static int
cl_blocked(int x, int y, int dx, int dy)
{
	int nx = x + dx, ny = y + dy, mx = nx + dx, my = ny + dy;

	if (nx < 0 || nx >= CL_W || ny < 0 || ny >= CL_H || cl_idx[ny][nx] >= 0)
		return 1;
	return mx >= 0 && mx < CL_W && my >= 0 && my < CL_H && cl_idx[my][mx] >= 0;
}

/* Lay out the spiral; cl_idx and cl_path are read-only afterwards. */
static void
cl_path_init(void)
{
	int x = 0, y = 0, dx = 1, dy = 0, i, t;

	memset(cl_idx, 0xff, sizeof cl_idx);
	for (i = 0; i < CL_PATHLEN; i++) {
		cl_path[i][0] = (short)x;
		cl_path[i][1] = (short)y;
		cl_idx[y][x] = (short)i;
		if (cl_blocked(x, y, dx, dy)) {
			t = dx;		/* a right turn on a screen with y down */
			dx = -dy;
			dy = t;
		}
		x += dx;
		y += dy;
	}
}

/*
 * The cell the shot line reaches at step t (t >= 1) from the launcher in
 * direction d, by stepping the longer axis one cell per step and rounding
 * the shorter one: offset = (2 t s + m) / (2 m) for shorter delta s and
 * longer delta m. Returns 0 when the cell is outside the field.
 */
static int
cl_ray_cell(int d, int t, int *x, int *y)
{
	int dx = cl_dir[d][0], dy = cl_dir[d][1];
	int ax = dx < 0 ? -dx : dx, ay = dy < 0 ? -dy : dy;
	int m = ax > ay ? ax : ay;
	int ox = (2 * t * ax + m) / (2 * m), oy = (2 * t * ay + m) / (2 * m);

	*x = CL_LX + (dx < 0 ? -ox : ox);
	*y = CL_LY + (dy < 0 ? -oy : oy);
	return *x >= 0 && *x < CL_W && *y >= 0 && *y < CL_H;
}

/* Index of the ball standing on path cell idx, or -1. */
static int
cl_ball_on(const struct cl_game *g, int idx)
{
	int k;

	for (k = 0; k < g->n; k++)
		if (g->pos[k] == idx)
			return k;
	return -1;
}

/*
 * Follow the shot line from the launcher and return the index of the first
 * ball it meets, or -1 when it leaves the field. *px, *py receive the last
 * cell before the ball (the launcher cell when the first cell holds it).
 */
static int
cl_trace(const struct cl_game *g, int d, int *px, int *py)
{
	int t, x, y, idx, k;

	*px = CL_LX;
	*py = CL_LY;
	for (t = 1; cl_ray_cell(d, t, &x, &y); t++) {
		idx = cl_idx[y][x];
		if (idx >= 0) {
			k = cl_ball_on(g, idx);
			if (k >= 0)
				return k;
		}
		*px = x;
		*py = y;
	}
	return -1;
}

static int
cl_dist2(int idx, int x, int y)
{
	int dx = cl_path[idx][0] - x, dy = cl_path[idx][1] - y;

	return dx * dx + dy * dy;
}

/*
 * The insertion index for a shot that met ball k after coming from cell
 * (px, py): k puts the new ball ahead of k, k + 1 behind it. The slot whose
 * path cell, next to ball k on the front or the back side, lies nearer to
 * (px, py) wins; a tie goes behind, and the end of the path leaves only
 * one slot.
 */
static int
cl_slot(const struct cl_game *g, int k, int px, int py)
{
	int p = g->pos[k];

	if (p + 1 > CL_PATHLEN - 1)
		return k + 1;
	if (p - 1 < 0)
		return k;
	return cl_dist2(p + 1, px, py) < cl_dist2(p - 1, px, py) ? k : k + 1;
}

/*
 * Put color c into the chain beside ball k, ahead of it when m is k and
 * behind it when m is k + 1. Behind, the new ball takes the cell after k
 * when that is free and k's own cell otherwise; ahead, it takes the cell
 * before k. Balls in front of the new one that it overlaps are pushed one
 * cell, each pushing the next, until a gap absorbs the push. *plo and *phi
 * receive the path cells whose neighbors changed: from the new ball's cell
 * to one past the last pushed ball. Returns the index of the new ball.
 */
static int
cl_insert(struct cl_game *g, int m, int k, int c, int *plo, int *phi)
{
	int s, j, prev;

	if (m == k) {
		s = g->pos[k] + 1;
	} else if (g->pos[k] > 0 && (k + 1 == g->n || g->pos[k + 1] < g->pos[k] - 1)) {
		s = g->pos[k] - 1;
	} else {
		s = g->pos[k];
	}
	memmove(&g->col[m + 1], &g->col[m], (size_t)(g->n - m));
	memmove(&g->pos[m + 1], &g->pos[m], (size_t)(g->n - m) * sizeof g->pos[0]);
	g->n++;
	g->col[m] = (unsigned char)c;
	g->pos[m] = (short)s;
	prev = s;
	for (j = m - 1; j >= 0 && g->pos[j] <= prev; j--)
		prev = g->pos[j] = (short)(prev + 1);
	*plo = s;
	*phi = prev + 1;
	return m;
}

/*
 * The run of equal colors that touches ball k with no gap inside it, as
 * the index range a..b.
 */
static void
cl_run(const struct cl_game *g, int k, int *a, int *b)
{
	int lo = k, hi = k;

	while (lo > 0 && g->pos[lo - 1] - g->pos[lo] == 1 && g->col[lo - 1] == g->col[k])
		lo--;
	while (hi < g->n - 1 && g->pos[hi] - g->pos[hi + 1] == 1 && g->col[hi + 1] == g->col[k])
		hi++;
	*a = lo;
	*b = hi;
}

static void
cl_add_score(struct cl_game *g, unsigned long pts)
{
	g->score += pts;
	if (g->score > CL_SCORE_MAX)
		g->score = CL_SCORE_MAX;
}

/* Remove balls a..b and score them: 10 each, times the combo count. */
static void
cl_remove(struct cl_game *g, int a, int b)
{
	int cnt = b - a + 1;

	cl_add_score(g, 10UL * (unsigned long)cnt * (unsigned long)g->combo);
	memmove(&g->col[a], &g->col[b + 1], (size_t)(g->n - b - 1));
	memmove(&g->pos[a], &g->pos[b + 1], (size_t)(g->n - b - 1) * sizeof g->pos[0]);
	g->n -= cnt;
}

/*
 * Remove every run of three or more equal colors that touches a ball on
 * path cells plo..phi. Each run raises the combo count first, so a second
 * run found in the same sweep scores one step higher. Returns the number
 * of runs removed.
 */
static int
cl_sweep(struct cl_game *g, int plo, int phi)
{
	int p, k, a, b, cleared = 0;

	for (p = plo; p <= phi; p++) {
		k = cl_ball_on(g, p);
		if (k < 0)
			continue;
		cl_run(g, k, &a, &b);
		if (b - a + 1 >= 3) {
			g->combo++;
			cl_remove(g, a, b);
			cleared++;
		}
	}
	return cleared;
}

/* Set the level outcome after any change to the chain. */
static void
cl_judge(struct cl_game *g)
{
	if (g->n > 0 && g->pos[0] >= CL_PATHLEN - 1)
		g->state = CL_LOST;
	else if (g->n == 0 && g->supply == 0)
		g->state = CL_WON;
}

/* (rand() * m) >> 15 takes the high bits of the 15-bit libc generator. */
static int
cl_rnd(int m)
{
	long v = rand();

#if RAND_MAX > 0x7fff
	v >>= 16;
	v &= 0x7fff;
#endif
	return (int)((v * m) >> 15);
}

/* The color of the next ball to enter: the script in order, else random
 * but never the third of a run. */
static int
cl_pick_spawn(struct cl_game *g)
{
	int c;

	if (g->spawn_script)
		return g->spawn_script[g->spawn_at++] - '0';
	c = 1 + g->draw(g->ncol);
	if (g->n >= 2 && g->col[g->n - 1] == c && g->col[g->n - 2] == c)
		c = c % g->ncol + 1;
	return c;
}

/* The color of the next shot: the script repeated, else a random color
 * that is still on the path (any color when the path is empty). */
static int
cl_pick_shot(struct cl_game *g)
{
	unsigned present = 0;
	int k, c, nth, cnt = 0;

	if (g->shot_script) {
		c = g->shot_script[g->shot_at++] - '0';
		if (g->shot_script[g->shot_at] == 0)
			g->shot_at = 0;
		return c;
	}
	for (k = 0; k < g->n; k++)
		present |= 1U << g->col[k];
	if (!present)
		return 1 + g->draw(g->ncol);
	for (c = 1; c <= CL_NCOL; c++)
		cnt += (present >> c) & 1U;
	nth = g->draw(cnt);
	for (c = 1; c <= CL_NCOL; c++)
		if (((present >> c) & 1U) && nth-- == 0)
			return c;
	return 1;
}

/*
 * Begin a level. The spawn and shot scripts and the draw function stay as
 * the caller set them; a spawn script is the whole supply.
 */
static void
cl_new(struct cl_game *g, int level, int adv_ticks)
{
	g->n = 0;
	g->level = level;
	g->ncol = 3 + (level >= 3) + (level >= 6);
	g->supply = g->spawn_script ? (int)strlen(g->spawn_script) : 20 + 6 * level;
	g->adv_ticks = adv_ticks > 0 ? adv_ticks : (level >= 8 ? 2 : 10 - level);
	g->clock = 0;
	g->combo = 0;
	g->dir = 0;
	g->state = CL_PLAY;
	g->spawn_at = g->shot_at = 0;
	g->shot = cl_pick_shot(g);
	g->next = cl_pick_shot(g);
}

static void
cl_turn(struct cl_game *g, int steps)
{
	g->dir = (g->dir + steps) & (CL_NDIR - 1);
}

/*
 * Fire the loaded ball along the launcher direction. Returns 1 when it
 * joined the chain and 0 when the line left the field. A run of three or
 * more equal colors that the new ball or a push completes vanishes with
 * combo 1.
 */
static int
cl_fire(struct cl_game *g)
{
	int px, py, m, c, hit, plo, phi;

	if (g->state != CL_PLAY)
		return 0;
	c = g->shot;
	hit = cl_trace(g, g->dir, &px, &py);
	if (hit >= 0) {
		m = cl_slot(g, hit, px, py);
		cl_insert(g, m, hit, c, &plo, &phi);
		g->combo = 0;
		cl_sweep(g, plo, phi);
		cl_judge(g);
	}
	g->shot = g->next;
	g->next = cl_pick_shot(g);
	return hit >= 0;
}

/*
 * The index of the first ball that stands behind a gap, or 0 when the
 * chain has none.
 */
static int
cl_first_gap(const struct cl_game *g)
{
	int k;

	for (k = 1; k < g->n; k++)
		if (g->pos[k - 1] - g->pos[k] > 1)
			return k;
	return 0;
}

/* One tick of the clock. */
static void
cl_tick(struct cl_game *g)
{
	int moves[CL_MAXB], before[CL_MAXB], k;

	if (g->state != CL_PLAY)
		return;
	if (cl_first_gap(g)) {
		/* The part ahead of the first gap holds; every part behind a
		 * gap rolls forward one cell. */
		for (k = 1; k < g->n; k++)
			before[k] = g->pos[k - 1] - g->pos[k];
		moves[0] = 0;
		for (k = 1; k < g->n; k++)
			moves[k] = before[k] > 1 ? 1 : moves[k - 1];
		for (k = 1; k < g->n; k++)
			if (moves[k])
				g->pos[k]++;
		/* A gap that just closed rejoins two parts: equal colors make
		 * a run, and a run of three vanishes one combo step higher. */
		for (k = 1; k < g->n; k++)
			if (before[k] > 1 && g->pos[k - 1] - g->pos[k] == 1) {
				if (!cl_sweep(g, g->pos[k], g->pos[k - 1]))
					g->combo = 0;
				break;
			}
		cl_judge(g);
		return;
	}
	g->combo = 0;
	if (++g->clock < g->adv_ticks)
		return;
	g->clock = 0;
	for (k = 0; k < g->n; k++)
		g->pos[k]++;
	if (g->supply > 0) {
		g->col[g->n] = (unsigned char)cl_pick_spawn(g);
		g->pos[g->n] = 0;
		g->n++;
		g->supply--;
	}
	cl_judge(g);
}

