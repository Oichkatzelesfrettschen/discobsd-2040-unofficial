#include <wchar.h>

/*
 * C17 7.29.4.5.2: the length of the initial segment free of wide
 * characters from reject.
 */
size_t
wcscspn(const wchar_t *s, const wchar_t *reject)
{
	size_t n = 0;

	while (s[n] != L'\0' && wcschr(reject, s[n]) == NULL)
		n++;
	return n;
}
