"""Hold the assembler and linker to byte-identical output and few file writes.

Every 1 KiB block the root file system writes costs flash erases, and a
temporary file costs several block writes of directory and inode traffic
before it holds a byte. usr.bin/as keeps its segments and relocation streams
in a bounded memory budget and usr.bin/ld writes text and data at their final
offsets in the output; neither creates a temporary file for a small program.

The gate compiles both tools from the tree and checks two things.

Identity: the objects and executables of a fixed set of inputs (generated by
gen_inputs.py) hash to the values in expected.json, which the tools of base
commit 270422ca produced, except the four outputs that pass through ld -r:
those are the tree's linker's, which leaves an unallocated common symbol
common in a relocatable link. The set spans a stream that stays in memory, a
stream that outgrows the assembler's budget, a segment larger than the
linker's relocation buffer, archive members, -s, -x, -X and -r, and a link of
a partial link.

Cost: the write, lseek, file-creation, unlink and ftruncate calls that
strace sees in one assembly and two links stay under the ceilings below. Each
ceiling sits above the count of this tree's tools, with room for another C
library's buffering, and below the count of the tools of the base commit, so a
return to per-stream temporary files or to per-relocation seeks fails it.

Calibration: an assembler built with a zero stream budget, a linker built
with a zero relocation buffer and a linker that sends its symbol records
through a temporary file again reproduce the identical bytes and must exceed
the ceilings; a linker whose data region starts four bytes late must
change the bytes. A gate that passed those would measure nothing.
"""

import argparse
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent

# Ceilings per command: calls that strace reports for one run. "base" is the
# count of the tools of commit 270422ca on the same inputs (glibc 2.4x,
# Linux x86-64); "tree" is the count of this tree's tools.
#
#   command                       write lseek create unlink ftruncate
#   as small.s            base       95    306     14     12      6
#                         tree        2      3      1      0      0
#   ld small.o mid.o lib1.o base    124    398      5      3      0
#                         tree        4     46      1      0      0
#   ld -r small.o mid.o   base       84    265      7      5      0
#                         tree        7     36      5      3      0   (temps stay)
CEILINGS = {
    "as-small": {"write": 6, "lseek": 12, "create": 1, "unlink": 0, "ftruncate": 0},
    "ld-link": {"write": 12, "lseek": 120, "create": 1, "unlink": 0, "ftruncate": 0},
    "ld-partial": {"write": 20, "lseek": 100, "create": 5, "unlink": 3, "ftruncate": 0},
}
TRACED = "write,lseek,open,openat,creat,unlink,unlinkat,ftruncate"


def digest(path):
    path = Path(path)
    if not path.exists():
        return "missing"
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command, cwd, check=True):
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True,
                            timeout=300, check=False)
    if check and result.returncode != 0:
        raise RuntimeError("%s failed (%d): %s%s" % (
            shlex.join(map(str, command)), result.returncode,
            result.stdout, result.stderr))
    return result


def libbsd_flags():
    if not sys.platform.startswith("linux"):
        return []
    return shlex.split(subprocess.check_output(
        ["pkg-config", "--cflags", "--libs", "libbsd-overlay"], text=True))


def compile_tool(source, binary, defines, work):
    """Compile one tool the way tools/aoututils does, with extra -D flags."""
    command = [*shlex.split(os.environ.get("CC", "cc")), "-std=gnu89",
               "-Wall", "-Wextra", "-Werror", "-fno-builtin", "-DCROSS",
               *defines,
               "-I" + str(ROOT / "tools/aoututils/include"),
               "-idirafter", str(ROOT / "include"),
               "-idirafter", str(ROOT / "tools/aoututils/ar"),
               str(source), "-o", str(binary), *libbsd_flags()]
    result = subprocess.run(command, capture_output=True, text=True, check=False,
                            timeout=300, cwd=work)
    if result.returncode or result.stderr:
        raise RuntimeError("compile %s:\n%s%s" % (binary.name, result.stdout, result.stderr))


def mutate(source_path, edits, work, name):
    text = source_path.read_text()
    for old, new in edits:
        if text.count(old) != 1:
            raise RuntimeError("mutation anchor differs: " + name)
        text = text.replace(old, new)
    path = work / (name + ".c")
    path.write_text(text)
    return path


def scenarios(as_bin, ld_bin, ar_bin, work, strict=True):
    """Produce every output of the fixed set and return {name: sha256}.

    strict makes any nonzero exit of the assembler or linker an error; only
    a calibration mutant that is expected to fail runs without it.
    """
    out = {}
    for name in ("small", "mid", "big", "lib1", "lib2", "unused"):
        run([as_bin, name + ".s", "-o", name + ".o"], work)
        out["as " + name + ".o"] = digest(work / (name + ".o"))
    run([as_bin, "-x", "big.s", "-o", "big-x.o"], work)
    out["as -x big.o"] = digest(work / "big-x.o")
    run([as_bin, "-X", "mid.s", "-o", "mid-X.o"], work)
    out["as -X mid.o"] = digest(work / "mid-X.o")
    archive = work / "lib.a"
    if archive.exists():
        archive.unlink()
    run([ar_bin, "rc", "lib.a", "lib1.o", "lib2.o", "unused.o"], work)
    links = {
        "link small mid lib": ["small.o", "mid.o", "lib.a"],
        "link small big lib": ["small.o", "big.o", "lib.a"],
        "link big mid small lib": ["big.o", "mid.o", "small.o", "lib.a"],
        "link -s mid": ["-s", "small.o", "mid.o", "lib.a"],
        "link -x mid": ["-x", "small.o", "mid.o", "lib.a"],
        "link -X big": ["-X", "small.o", "big.o", "lib.a"],
        "link -r small mid": ["-r", "small.o", "mid.o"],
        "link -r small big": ["-r", "small.o", "big.o"],
        "link -r -x small mid": ["-r", "-x", "small.o", "mid.o"],
    }
    for name, arguments in links.items():
        target = "out-" + re.sub(r"\W+", "-", name) + ".out"
        run([ld_bin, "-o", target, *arguments], work, check=strict)
        out["ld " + name] = digest(work / target)
    # A partial link is a valid input of a later link.
    run([ld_bin, "-r", "-o", "part.o", "small.o", "mid.o"], work, check=strict)
    run([ld_bin, "-o", "out-final.out", "part.o", "big.o", "lib.a"], work, check=strict)
    out["ld partial then final"] = digest(work / "out-final.out")
    return out


def under_umask(mask):
    def apply():
        os.umask(mask)
    return apply


def umask_case(as_bin, ld_bin, work, expected):
    """Assemble and link under umask 0222; return the problems found.

    A umask without owner write creates the output 0444, which a reopen for
    update refuses unless the tool holds write access itself. The linker's
    bytes must be the base tool's and its final mode 0777 & ~umask, which the
    base delexit() sets. Neither base tool can run under this umask on a
    host whose mkstemp applies it (each reopens its temporary file by name),
    so the base bytes come from a run under the ordinary umask and the modes
    from the creation rules: the assembler's output keeps 0444.
    """
    problems = []
    for name in ("small", "mid", "lib1"):
        run([as_bin, name + ".s", "-o", name + ".o"], work)
    result = subprocess.run(
        [as_bin, "small.s", "-o", "locked.o"], cwd=work, capture_output=True,
        text=True, check=False, timeout=300, preexec_fn=under_umask(0o222))
    if result.returncode != 0:
        problems.append("as under umask 0222 exited %d" % result.returncode)
    elif oct(os.stat(work / "locked.o").st_mode & 0o777) != oct(0o444):
        problems.append("as under umask 0222 left mode %s" % oct(
            os.stat(work / "locked.o").st_mode & 0o777))
    result = subprocess.run(
        [ld_bin, "-o", "locked.out", "small.o", "mid.o", "lib1.o"], cwd=work,
        capture_output=True, text=True, check=False, timeout=300,
        preexec_fn=under_umask(0o222))
    target = work / "locked.out"
    if result.returncode != 0:
        problems.append("ld under umask 0222 exited %d: %s" % (
            result.returncode, result.stdout.strip()))
    elif digest(target) != expected["umask_modes"]["ld digest"]:
        problems.append("ld under umask 0222 changed the bytes")
    elif os.stat(target).st_mode & 0o777 != 0o777 & ~0o222:
        problems.append("ld under umask 0222 left mode %s, base leaves %s" % (
            oct(os.stat(target).st_mode & 0o777), oct(0o777 & ~0o222)))
    # A relocatable link over an existing file keeps that file's mode, as
    # the base tool's truncating open does.
    kept = work / "kept.o"
    kept.write_bytes(b"")
    os.chmod(kept, 0o600)
    result = subprocess.run(
        [ld_bin, "-r", "-o", "kept.o", "small.o", "mid.o"], cwd=work,
        capture_output=True, text=True, check=False, timeout=300)
    if result.returncode != 0:
        problems.append("ld -r over an existing file exited %d: %s" % (
            result.returncode, result.stdout.strip()))
    elif os.stat(kept).st_mode & 0o777 != 0o600:
        problems.append("ld -r over a mode 0600 file left mode %s" % oct(
            os.stat(kept).st_mode & 0o777))
    return problems


def strace_usable():
    exe = shutil.which("strace")
    if not exe:
        return None
    probe = subprocess.run([exe, "-o", os.devnull, "-e", "trace=write", "true"],
                           capture_output=True, check=False)
    return exe if probe.returncode == 0 else None


def count_calls(strace, command, work):
    log = work / "strace.log"
    result = subprocess.run([strace, "-o", str(log), "-e", "trace=" + TRACED,
                             *map(str, command)], cwd=work, capture_output=True,
                            text=True, check=False, timeout=300)
    if result.returncode != 0:
        raise RuntimeError("traced command exited %d: %s" % (result.returncode,
                                                            result.stderr))
    counts = {"write": 0, "lseek": 0, "create": 0, "unlink": 0, "ftruncate": 0}
    for line in log.read_text().splitlines():
        match = re.match(r"(\w+)\(", line)
        if not match:
            continue
        call = match.group(1)
        if call in ("write", "lseek", "ftruncate"):
            counts[call] += 1
        elif call in ("unlink", "unlinkat"):
            counts["unlink"] += 1
        elif call in ("open", "openat", "creat") and \
                ("O_CREAT" in line or call == "creat"):
            counts["create"] += 1
    return counts


def measure(strace, as_bin, ld_bin, work):
    """Return the counts of the three ceiling commands."""
    run([as_bin, "small.s", "-o", "small.o"], work)
    run([as_bin, "mid.s", "-o", "mid.o"], work)
    run([as_bin, "lib1.s", "-o", "lib1.o"], work)
    return {
        "as-small": count_calls(strace, [as_bin, "small.s", "-o", "small.o"], work),
        "ld-link": count_calls(strace, [ld_bin, "-o", "t.out", "small.o", "mid.o",
                                        "lib1.o"], work),
        "ld-partial": count_calls(strace, [ld_bin, "-r", "-o", "t.o", "small.o",
                                           "mid.o"], work),
    }


def over_ceiling(counts):
    problems = []
    for command, ceiling in CEILINGS.items():
        for call, limit in ceiling.items():
            if counts[command][call] > limit:
                problems.append("%s: %s %d > %d" % (command, call,
                                                    counts[command][call], limit))
    return problems


def record(args):
    work = Path(tempfile.mkdtemp(prefix="as-ld-scratch-"))
    try:
        run([sys.executable, HERE / "gen_inputs.py", work], work)
        inputs = {p.name: digest(p) for p in sorted(work.glob("*.s"))}
        as_bin = str(Path(args.as_bin).resolve())
        ld_bin = str(Path(args.ld_bin).resolve())
        outputs = scenarios(as_bin, ld_bin, str(Path(args.ar).resolve()), work)
        locked = work / "locked"
        locked.mkdir()
        for name in ("small", "mid", "lib1"):
            shutil.copy(work / (name + ".s"), locked)
            run([as_bin, name + ".s", "-o", name + ".o"], locked)
        subprocess.run([ld_bin, "-o", "locked.out", "small.o", "mid.o", "lib1.o"],
                       cwd=locked, check=True)
        modes = {"ld digest": digest(locked / "locked.out")}
        (HERE / "expected.json").write_text(json.dumps({
            "provenance": args.provenance, "inputs": inputs, "outputs": outputs,
            "umask_modes": modes}, indent=2, sort_keys=True) + "\n")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    print("recorded %d outputs" % len(outputs))
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ar", default=str(ROOT / "tools/aoututils/ar/ar"))
    parser.add_argument("--record", action="store_true")
    parser.add_argument("--as-bin")
    parser.add_argument("--ld-bin")
    parser.add_argument("--provenance", default="")
    args = parser.parse_args()
    if args.record:
        return record(args)
    if not sys.platform.startswith("linux"):
        print("SKIP as-ld-scratch: strace is Linux only; no verdict on a "
              "%s host" % sys.platform)
        return 0
    strace = strace_usable()
    if not strace:
        print("FAIL as-ld-scratch: strace missing or ptrace denied "
              "(package strace); the call counts did not run")
        return 1
    expected = json.loads((HERE / "expected.json").read_text())
    work = Path(tempfile.mkdtemp(prefix="as-ld-scratch-"))
    try:
        return gate(args, strace, expected, work)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def gate(args, strace, expected, work):
    inputs_dir = work / "inputs"
    inputs_dir.mkdir()
    run([sys.executable, HERE / "gen_inputs.py", inputs_dir], work)
    inputs = {p.name: digest(p) for p in sorted(inputs_dir.glob("*.s"))}
    if inputs != expected["inputs"]:
        print("FAIL as-ld-scratch: gen_inputs.py no longer produces the "
              "inputs expected.json was recorded from")
        return 1

    build = work / "build"
    build.mkdir()
    as_src = ROOT / "usr.bin/as/as-thumb.c"
    ld_src = ROOT / "usr.bin/ld/ld.c"
    late_data = mutate(ld_src, [(
        "tregion (&doutb, HDRSZ + (unsigned long) tsize);",
        "tregion (&doutb, HDRSZ + (unsigned long) tsize + 4);")],
        build, "ld-late-data")
    # Correct bytes with a failing exit status.
    exit_fail = mutate(ld_src, [("delarg = errlev;", "delarg = 3;")], build,
                       "ld-exit-3")
    # A reopen for update with no owner write access held.
    plain_reopen = mutate(ld_src, [("\tchmod (ofilename, outmode | 0200);\n", "")],
                          build, "ld-plain-reopen")
    # The old path for the symbol records: a temporary file, copied after
    # the data. The bytes stay the same; the file creations and the unlink
    # come back.
    temp_symbols = mutate(ld_src, [
        ("\t\ttregion (&soutb, tail);\n\t\ttailb = soutb;",
         "\t\ttregion (&tailb, tail);\n\t\tclose (mkstemp (tfname));\n"
         "\t\ttcreat (&soutb, 1);"),
        ("\t\tif (output_relinfo) {\n\t\t\tif (! xflag)\n"
         "\t\t\t\tcopy_and_close (soutb, tailb);",
         "\t\tif (1) {\n\t\t\tif (! xflag)\n"
         "\t\t\t\tcopy_and_close (soutb, tailb);")],
        build, "ld-temp-symbols")
    variants = {
        "candidate": (as_src, [], ld_src, []),
        "as-budget-1024": (as_src, ["-DSCRATCH_BUDGET=1024"], ld_src, []),
        "as-budget-0": (as_src, ["-DSCRATCH_BUDGET=0"], ld_src, []),
        "ld-buffer-0": (as_src, [], ld_src, ["-DRELOC_BUFFER=0"]),
        "ld-buffer-4096": (as_src, [], ld_src, ["-DRELOC_BUFFER=4096"]),
        "ld-temp-symbols": (as_src, [], temp_symbols, []),
    }
    tools = {}
    for name, (asrc, adef, lsrc, ldef) in variants.items():
        tools[name] = (build / (name + "-as"), build / (name + "-ld"))
        compile_tool(asrc, tools[name][0], adef, build)
        compile_tool(lsrc, tools[name][1], ldef, build)
    late_ld = build / "late-data-ld"
    compile_tool(late_data, late_ld, [], build)
    exit_ld = build / "exit-3-ld"
    compile_tool(exit_fail, exit_ld, [], build)
    reopen_ld = build / "plain-reopen-ld"
    compile_tool(plain_reopen, reopen_ld, [], build)

    failures = []
    ar_bin = str(Path(args.ar).resolve())
    for name, (as_bin, ld_bin) in tools.items():
        run_dir = work / ("run-" + name)
        shutil.copytree(inputs_dir, run_dir)
        try:
            got = scenarios(str(as_bin), str(ld_bin), ar_bin, run_dir)
        except RuntimeError as error:
            failures.append("%s: %s" % (name, str(error).splitlines()[0]))
            continue
        for key, value in got.items():
            if expected["outputs"].get(key) != value:
                failures.append("%s: %s differs from the recorded bytes" % (name, key))
        print("identity %-16s %d outputs checked" % (name, len(got)))

    # Known-bad for the identity check: a linker whose data region starts
    # four bytes late.
    bad_dir = work / "run-late-data"
    shutil.copytree(inputs_dir, bad_dir)
    bad = scenarios(str(tools["candidate"][0]), str(late_ld), ar_bin, bad_dir,
                    strict=False)
    changed = [k for k, v in bad.items() if expected["outputs"].get(k) != v]
    if not changed:
        failures.append("calibration: a linker with a late data region matched every digest")
    else:
        print("calibration: late-data linker changes %d outputs, rejected" % len(changed))

    # Known-bad for the exit status: the bytes are right and the linker
    # reports failure.
    exit_dir = work / "run-exit-3"
    shutil.copytree(inputs_dir, exit_dir)
    lax = scenarios(str(tools["candidate"][0]), str(exit_ld), ar_bin, exit_dir,
                    strict=False)
    if any(expected["outputs"].get(k) != v for k, v in lax.items()):
        failures.append("calibration: the exit-3 linker changed bytes")
    try:
        scenarios(str(tools["candidate"][0]), str(exit_ld), ar_bin,
                  work / "run-exit-3", strict=True)
        failures.append("calibration: a linker with correct bytes and exit 3 passed")
    except RuntimeError:
        print("calibration: correct bytes with exit 3 rejected")

    if os.geteuid() == 0:
        print("SKIP umask case: running as root, which ignores file modes; "
              "no verdict on a restrictive umask")
    else:
        for name, ld_bin in (("candidate", tools["candidate"][1]),
                             ("plain-reopen", reopen_ld)):
            umask_dir = work / ("umask-" + name)
            shutil.copytree(inputs_dir, umask_dir)
            found = umask_case(str(tools["candidate"][0]), str(ld_bin), umask_dir,
                               expected)
            if name == "candidate":
                for message in found:
                    failures.append("umask 0222: " + message)
                print("umask 0222: candidate " +
                      ("fails" if found else "links, bytes and mode as base"))
            elif found:
                print("calibration: plain r+ reopen fails under umask 0222, rejected")
            else:
                failures.append("calibration: a plain r+ reopen survived umask 0222")

    counts = {}
    for name in ("candidate", "as-budget-0", "ld-buffer-0", "ld-temp-symbols"):
        measure_dir = work / ("count-" + name)
        shutil.copytree(inputs_dir, measure_dir)
        counts[name] = measure(strace, str(tools[name][0]), str(tools[name][1]),
                               measure_dir)
        print("counts %-12s %s" % (name, json.dumps(counts[name], sort_keys=True)))
    for problem in over_ceiling(counts["candidate"]):
        failures.append("candidate exceeds its ceiling: " + problem)
    # Known-bad for the ceilings: the old path (a stream per file, a seek per
    # relocation) must trip them while producing the same bytes.
    for name in ("as-budget-0", "ld-buffer-0", "ld-temp-symbols"):
        if not over_ceiling(counts[name]):
            failures.append("calibration: %s stayed under every ceiling" % name)
        else:
            print("calibration: %s exceeds the ceilings, rejected" % name)

    for message in failures:
        print("FAIL as-ld-scratch: " + message)
    if failures:
        return 1
    print("PASS as-ld-scratch")
    return 0


if __name__ == "__main__":
    sys.exit(main())
