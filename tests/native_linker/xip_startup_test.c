#include <stdlib.h>
#include <string.h>
#include <unistd.h>

extern char _end[];

int
main(int argc, char **argv, char **envp)
{
	const char *home;

	if (argc != 2 || argv[2] != NULL || envp != environ)
		return 1;
	if (strcmp(__progname, argv[1]) != 0 || argv[0][0] != '/')
		return 2;
	home = getenv("HOME");
	if (home == NULL || strcmp(home, "/home/operator") != 0)
		return 3;
	if (sbrk(0) != _end)
		return 4;
	return 37;
}
