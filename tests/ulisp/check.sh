# usage: check.sh host|qemu DOCFILE COMMAND [ARG...]
#
# Runs the uLisp that COMMAND starts over the corpora of this directory, in
# a directory of its own, and compares each transcript with its .expected
# file. host runs the language, system, images, repairs, arith, types and
# devices corpora (arith.lisp and types.lisp are generated by gen-arith.py and
# gen-types.py into the work directory; types must also hold no "memory
# fault", the interpreter's own report of a wild pointer);
# qemu runs the first four and, in place of devices, the stack and
# machine-code corpora that need the target. Both reload the image the
# system corpus saved in a second process with a smaller workspace, which
# rebases it. The images corpus loads damaged copies of that image
# (corrupt-image.py, which needs PYTHON) and requires each to be refused
# with the workspace unchanged.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
mode=$1
doc=$2
shift 2

work=$(mktemp -d "${TMPDIR:-/tmp}/ulisp-check.XXXXXX")
trap 'rm -rf "$work"' EXIT HUP INT TERM
cd "$work"

status=0
# run NAME CELLS [OPTION...]: one corpus, compared with NAME.expected
run() {
	name=$1
	cells=$2
	shift 2
	input=$here/$name.lisp
	if [ -f "$name.lisp" ]; then
		input=$name.lisp
	fi
	rc=0
	env -i ULISPLIB="$here/library.lisp" ULISPDOC="$doc" \
	    "$@" -w "$cells" < "$input" > "$name.out" 2>&1 || rc=$?
	# 124 is timeout(1) ending a run that did not finish; 126 and 127
	# are a command that could not be started. Neither is a transcript
	# verdict, so the check ends at once with status 3 (did not finish)
	# or 4 (did not start), apart from the status 1 of a failed or
	# differing transcript.
	case $rc in
	0)	;;
	124)	echo "ulisp $mode: $name: the run did not finish in its time" >&2
		exit 3 ;;
	126|127)
		echo "ulisp $mode: $name: the command did not start (status $rc)" >&2
		exit 4 ;;
	*)	echo "ulisp $mode: $name: the interpreter failed" >&2
		status=1 ;;
	esac
}
compare() {
	if ! diff "$here/$1.expected" "$1.out" > "$1.diff"; then
		echo "ulisp $mode: $1 differs from $1.expected:" >&2
		head -20 "$1.diff" >&2
		status=1
	fi
}

case $mode in
host)	corpora="language system images repairs arith types devices" ;;
qemu)	corpora="language system images repairs stack code" ;;
*)	echo "usage: check.sh host|qemu DOCFILE COMMAND [ARG...]" >&2; exit 2 ;;
esac

for corpus in $corpora; do
	if [ "$corpus" = images ]; then
		: "${PYTHON:?set PYTHON to the intended interpreter}"
		"$PYTHON" -I "$here/corrupt-image.py" ulisp-test.img .
	fi
	if [ "$corpus" = arith ]; then
		: "${PYTHON:?set PYTHON to the intended interpreter}"
		"$PYTHON" -I "$here/gen-arith.py" "$(dirname "$doc")/builtins.def" > arith.lisp
	fi
	if [ "$corpus" = types ]; then
		: "${PYTHON:?set PYTHON to the intended interpreter}"
		"$PYTHON" -I "$here/gen-types.py" "$(dirname "$doc")/builtins.def" > types.lisp
	fi
	run "$corpus" 12000 "$@"
	if [ "$corpus" = types ] && grep -q 'memory fault' types.out; then
		echo "ulisp $mode: types: a form reported a memory fault:" >&2
		grep -B2 'memory fault' types.out | head -12 >&2
		status=1
	fi
	if [ "$corpus" = devices ]; then
		cksum < ulisp-test.bmp >> devices.out
	fi
	compare "$corpus"
done
run reload 9000 "$@" -i ulisp-test.img
compare reload
# The loader's second read of the image: the shim rewrites the file between
# the check and the install (race), so the load is refused only if the
# installed cells are checked, and cuts it short (truncrace), so the install
# fails and the workspace is rebuilt. They exist for the host run with a shim.
if [ "$mode" = host ] && [ -n "${ULISP_REWRITE_SHIM:-}" ]; then
	for race in race truncrace; do
		cp ulisp-test.img "$race.img"
		run "$race" 12000 env LD_PRELOAD="$ULISP_REWRITE_SHIM" "$@"
		compare "$race"
		corpora="$corpora $race"
	done
fi

# SIGINT while the interpreter waits for input ends the read with EINTR,
# which is no end of input: a form sent afterwards is still evaluated. The
# signal goes to the command and to its child, since a timeout(1) or env(1)
# in front of the interpreter may or may not pass it on.
if [ "$mode" = host ]; then
	mkfifo intr.fifo
	env -i ULISPLIB="$here/library.lisp" ULISPDOC="$doc" \
	    "$@" -w 9000 < intr.fifo > intr.out 2>&1 &
	pid=$!
	exec 9> intr.fifo
	sleep 1
	kill -INT "$pid" 2> /dev/null || true
	pkill -INT -P "$pid" 2> /dev/null || true
	sleep 1
	# An interpreter that has already exited leaves the pipe without a
	# reader; the write then fails here instead of ending this script.
	trap '' PIPE
	echo '(* 6 7)' >&9 2> /dev/null || true
	trap - PIPE
	exec 9>&-
	wait "$pid" || true
	if ! grep -q 42 intr.out; then
		echo "ulisp $mode: SIGINT at the prompt ended the session" >&2
		status=1
	fi
fi

if [ "$status" -eq 0 ]; then
	echo "ulisp $mode: $corpora reload: transcripts match"
fi
exit "$status"
