"""Generate the PicoCalc console font table from a fixed-cell BDF font.

Usage: bdf_font.py BDF OUTPUT        write OUTPUT
       bdf_font.py --check BDF OUTPUT  fail unless OUTPUT matches BDF

The BDF must carry every code from 32 to 126 as a 6-pixel-wide glyph whose
bounding box equals the font bounding box, so each glyph is FONT_HEIGHT
bytes with the leftmost pixel in bit 7. The table lcdfont[c - 32][row] is
what st7365p.c draws into a 6x10 cell; row 9 of the cell stays background,
and the underline attribute draws there.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

FIRST, LAST = 32, 126
WIDTH, HEIGHT = 6, 9

HEADER = """\
/*
 * Generated by tools/picocalc/bdf_font.py from
 * sys/arch/rp2040/dev/fonts/6x9-ascii.bdf, the ASCII subset of the
 * public-domain Misc-Fixed 6x9 font. Do not edit; regenerate.
 *
 * lcdfont[c - 32][row] holds one row of character c, leftmost pixel in
 * bit 7; only bits 7-2 are used.
 */

#include "lcdfont.h"

const unsigned char lcdfont[LCDFONT_NCHARS][LCDFONT_HEIGHT] = {
"""


def fail(message: str) -> None:
    raise SystemExit(f"bdf_font: {message}")


def parse(text: str) -> dict[int, list[int]]:
    glyphs: dict[int, list[int]] = {}
    lines = iter(text.splitlines())
    fbb = None
    for line in lines:
        words = line.split()
        if not words:
            continue
        if words[0] == "FONTBOUNDINGBOX":
            fbb = tuple(int(w) for w in words[1:5])
            if fbb[0] != WIDTH or fbb[1] != HEIGHT:
                fail(f"font bounding box {fbb[:2]} is not {WIDTH}x{HEIGHT}")
        elif words[0] == "STARTCHAR":
            encoding, bbx, rows = None, None, []
            for inner in lines:
                parts = inner.split()
                if not parts:
                    continue
                if parts[0] == "ENCODING":
                    encoding = int(parts[1])
                elif parts[0] == "BBX":
                    bbx = tuple(int(w) for w in parts[1:5])
                elif parts[0] == "BITMAP":
                    for row in lines:
                        if row.strip() == "ENDCHAR":
                            break
                        rows.append(int(row.strip(), 16))
                    break
            if encoding is None or bbx is None:
                fail("glyph without ENCODING or BBX")
            if FIRST <= encoding <= LAST:
                if bbx != fbb:
                    fail(f"glyph {encoding} box {bbx} differs from font box {fbb}")
                if len(rows) != HEIGHT:
                    fail(f"glyph {encoding} has {len(rows)} rows, not {HEIGHT}")
                if any(r & 0x03 for r in rows):
                    fail(f"glyph {encoding} sets a pixel right of column {WIDTH}")
                glyphs[encoding] = rows
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        fail(f"missing glyphs {missing}")
    return glyphs


def render(glyphs: dict[int, list[int]]) -> str:
    out = [HEADER]
    for code in range(FIRST, LAST + 1):
        rows = ", ".join("0x%02x" % r for r in glyphs[code])
        shown = chr(code) if chr(code) not in "\\'" else "\\" + chr(code)
        out.append("\t{ %s },\t/* '%s' */\n" % (rows, shown))
    out.append("};\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("bdf", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args(argv)
    generated = render(parse(args.bdf.read_text(encoding="ascii")))
    if args.check:
        current = args.output.read_text(encoding="ascii") if args.output.exists() else ""
        if current != generated:
            print(f"bdf_font: {args.output} differs from {args.bdf}; regenerate", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(generated, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
